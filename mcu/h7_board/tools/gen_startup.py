#!/usr/bin/env python3
"""从 CMSIS 器件头文件生成 GCC 启动汇编（向量表 + Reset_Handler）。

器件头 stm32h750xx.h 里的 IRQn_Type 枚举是向量表顺序的唯一来源；
换芯片/换 HAL 版本时重跑本脚本即可，避免手抄向量名错位。

用法：
    python tools/gen_startup.py <stm32h750xx.h> Core/Startup/startup_stm32h750xx.s
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

CORE_EXCEPTIONS = [
    ("_estack", "Top of Stack"),
    ("Reset_Handler", "Reset Handler"),
    ("NMI_Handler", "NMI Handler"),
    ("HardFault_Handler", "Hard Fault Handler"),
    ("MemManage_Handler", "MPU Fault Handler"),
    ("BusFault_Handler", "Bus Fault Handler"),
    ("UsageFault_Handler", "Usage Fault Handler"),
    ("0", "Reserved"),
    ("0", "Reserved"),
    ("0", "Reserved"),
    ("0", "Reserved"),
    ("SVC_Handler", "SVCall Handler"),
    ("DebugMon_Handler", "Debug Monitor Handler"),
    ("0", "Reserved"),
    ("PendSV_Handler", "PendSV Handler"),
    ("SysTick_Handler", "SysTick Handler"),
]


def parse_irqs(header: Path) -> list[tuple[str, int]]:
    text = header.read_text(encoding="gbk", errors="ignore")
    body = re.search(r"typedef\s+enum\s*\{(.*?)\}\s*IRQn_Type", text, re.S)
    if not body:
        raise SystemExit(f"未在 {header} 中找到 IRQn_Type 枚举")
    items = re.findall(r"([A-Za-z0-9_]+_IRQn)\s*=\s*(-?\d+)", body.group(1))
    return [(name, int(num)) for name, num in items]


def render(irqs: list[tuple[str, int]]) -> str:
    positive = [(n, v) for n, v in irqs if v >= 0]
    max_irq = max(v for _, v in positive) if positive else -1
    by_index: dict[int, str] = {v: n for n, v in positive}

    lines: list[str] = []
    lines.append("/**")
    lines.append(" * @file    startup_stm32h750xx.s")
    lines.append(" * @brief   GCC startup: vector table generated by tools/gen_startup.py, do not edit")
    lines.append(" */")
    lines.append("")
    lines.append("  .syntax unified")
    lines.append("  .cpu cortex-m7")
    lines.append("  .fpu fpv5-d16")
    lines.append("  .thumb")
    lines.append("")
    lines.append("  .section .isr_vector,\"a\",%progbits")
    lines.append("  .align 2")
    lines.append("  .globl g_pfnVectors")
    lines.append("  .type g_pfnVectors, %object")
    lines.append("g_pfnVectors:")
    for name, desc in CORE_EXCEPTIONS:
        lines.append(f"  .word {name:<28} /* {desc} */")
    for index in range(max_irq + 1):
        handler = by_index.get(index, "0")
        if handler.endswith("_IRQn"):
            handler = handler.replace("_IRQn", "_IRQHandler")
        lines.append(f"  .word {handler:<28} /* IRQ {index} */")
    lines.append("  .size g_pfnVectors, .-g_pfnVectors")
    lines.append("")
    lines.append("  .text")
    lines.append("  .thumb")
    lines.append("  .thumb_func")
    lines.append("  .globl Reset_Handler")
    lines.append("  .type Reset_Handler, %function")
    lines.append("Reset_Handler:")
    lines.append("  ldr   sp, =_estack")
    lines.append("  /* copy .data initial values from flash to RAM */")
    lines.append("  ldr   r0, =_sdata")
    lines.append("  ldr   r1, =_edata")
    lines.append("  ldr   r2, =_sidata")
    lines.append("1:")
    lines.append("  cmp   r0, r1")
    lines.append("  itt   lo")
    lines.append("  ldrlo r3, [r2], #4")
    lines.append("  strlo r3, [r0], #4")
    lines.append("  blo   1b")
    lines.append("  /* zero .bss */")
    lines.append("  ldr   r0, =_sbss")
    lines.append("  ldr   r1, =_ebss")
    lines.append("  movs  r3, #0")
    lines.append("2:")
    lines.append("  cmp   r0, r1")
    lines.append("  itt   lo")
    lines.append("  strlo r3, [r0], #4")
    lines.append("  blo   2b")
    lines.append("")
    lines.append("  bl    SystemInit")
    lines.append("  bl    __libc_init_array")
    lines.append("  bl    main")
    lines.append("  bx    lr")
    lines.append("  .size Reset_Handler, .-Reset_Handler")
    lines.append("")
    lines.append("  .text")
    lines.append("  .thumb_func")
    lines.append("  .weak Default_Handler")
    lines.append("  .type Default_Handler, %function")
    lines.append("Default_Handler:")
    lines.append("  b Default_Handler")
    lines.append("  .size Default_Handler, .-Default_Handler")
    lines.append("")
    for core_name in ("SVC_Handler", "PendSV_Handler"):
        lines.append(f"  .weak {core_name}")
        lines.append(f"  .thumb_set {core_name}, Default_Handler")
    for name, _value in irqs:
        if name.endswith("_IRQn") and not name.startswith(("NonMaskable", "HardFault", "MemoryManagement", "BusFault", "UsageFault", "SVCall", "DebugMonitor", "PendSV", "SysTick")):
            handler = name.replace("_IRQn", "_IRQHandler")
            lines.append(f"  .weak {handler}")
            lines.append(f"  .thumb_set {handler}, Default_Handler")
    lines.append("")
    return "\n".join(lines) + "\n"


def main() -> None:
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    out = Path(sys.argv[2])
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(parse_irqs(Path(sys.argv[1]))), encoding="ascii", newline="\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
